import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const projectRoot = path.resolve(__dirname, "..");

const componentsDir = path.resolve(
	projectRoot,
	"node_modules/prismjs/components",
);
const themesDir = path.resolve(projectRoot, "node_modules/prismjs/themes");
const outputPath = path.resolve(projectRoot, "src/generated/prism-assets.ts");

const toId = (filename) => filename.replace(/^prism-/, "").replace(/\.js$/, "");

const toThemeId = (filename) => {
	if (filename === "prism.css") return "default";
	return filename.replace(/^prism-/, "").replace(/\.css$/, "");
};

export const generatePrismAssets = async () => {
	const componentFiles = (await fs.readdir(componentsDir))
		.filter((name) => name.startsWith("prism-") && name.endsWith(".js"))
		.sort();

	const themeFiles = (await fs.readdir(themesDir))
		.filter((name) => name.endsWith(".css"))
		.sort();

	const languageEntries = componentFiles.map((name) => {
		const id = toId(name);
		return [
			"\t{",
			`\t\tid: ${JSON.stringify(id)},`,
			`\t\tmodule: () => import(${JSON.stringify(
				`prismjs/components/${name}`,
			)}),`,
			"\t},",
		].join("\n");
	});

	const themeEntries = [];
	for (const name of themeFiles) {
		const id = toThemeId(name);
		const css = await fs.readFile(path.resolve(themesDir, name), "utf-8");
		themeEntries.push(
			[
				"\t{",
				`\t\tid: ${JSON.stringify(id)},`,
				`\t\tcss: ${JSON.stringify(css)},`,
				"\t},",
			].join("\n"),
		);
	}

	const contents = `// This file is generated by scripts/generate-prism-assets.mjs. Do not edit.
// biome-ignore format: generated file
export const PRISM_LANGUAGES = [
${languageEntries.join("\n")}
];

// biome-ignore format: generated file
export const PRISM_THEMES = [
${themeEntries.join("\n")}
];
`;

	await fs.mkdir(path.dirname(outputPath), { recursive: true });
	await fs.writeFile(outputPath, contents);
};

if (import.meta.main) {
	await generatePrismAssets();
}
